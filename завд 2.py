text = "Python це чудова мова програмування. Вона була створена Гвідо ван Россумом. Київ це столиця України."

# Кількість символів (включаючи пробіли)
char_count = len(text)

# Кількість слів (розбиваємо по пробілах)
word_count = len(text.split())

# Кількість речень (рахуємо кількість крапок)
sentence_count = text.count(".")

# Виводимо результати
print("Кількість символів:", char_count)
print("Кількість слів:", word_count)
print("Кількість речень:", sentence_count)