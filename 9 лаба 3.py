import pandas as pd
from datetime import date

# Завантаження даних
try:
    df = pd.read_csv('nba_players (1).csv')
except FileNotFoundError:
    print("Помилка: Файл 'nba_players (1).csv' не знайдено.")
    exit()

# Константа для команди
TEAM_NAME = 'Sacramento Kings'

# 1. Фільтрація та підготовка даних
df_team = df[df['Team'] == TEAM_NAME].copy()

# Перейменування стовпців для зручності виводу (якщо потрібно)
df_team.columns = ['Ім\'я', 'Команда', 'Позиція', 'Дата народження', 'Зарплата']

# Перетворення 'Дата народження' на datetime
df_team['Дата народження'] = pd.to_datetime(df_team['Дата народження'], format='%m/%d/%y')

# Обчислення віку на фіксовану дату (наприклад, кінець 2025 року)
def calculate_age(birth_date):
    today = date(2025, 12, 17)
    # pandas Series.dt.year/month/day можна використовувати безпосередньо у функції apply
    return today.year - birth_date.year - ((today.month, today.day) < (birth_date.month, birth_date.day))

df_team['Вік'] = df_team['Дата народження'].apply(calculate_age)

# Налаштування форматування для зарплати
pd.options.display.float_format = '{:,.0f}'.format

print(f"--- Аналіз команди: {TEAM_NAME} ---\n")
print("-" * 60)

# ------------------------------------------------
# Операції
# ------------------------------------------------

# 1. Вивести всю інформацію про гравців в команді відсортовану за Name.
print("1. Вивести всю інформацію про гравців в команді відсортовану за Name.")
result_1 = df_team.sort_values(by='Ім\'я')
print(result_1[['Ім\'я', 'Позиція', 'Дата народження', 'Зарплата', 'Вік']])
print("-" * 60)

# 2. Вивести кількість гравців в команді.
print("2. Вивести кількість гравців в команді.")
