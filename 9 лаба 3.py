oldest = df_team.nlargest(3, 'Вік')[['Ім\'я', 'Вік', 'Дата народження']]
print("--- Наймолодші гравці ---")
print(youngest)
print("\n--- Найстарші гравці ---")
print(oldest)
print("-" * 60)

# 5. Вивести інформацію про 3-х гравців з найменшою і найбільшою зарплатою у команді.
print("5. Вивести інформацію про 3-х гравців з найменшою і найбільшою зарплатою у команді.")
