from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH


def create_report():
    doc = Document()

    # Налаштування стилю тексту за замовчуванням
    style = doc.styles['Normal']
    font = style.font
    font.name = 'Times New Roman'
    font.size = Pt(12)

    # Заголовок
    title = doc.add_heading('ЗВІТ З ЛАБОРАТОРНОЇ РОБОТИ', 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Мета та вступ
    doc.add_paragraph('Тема: Умовні оператори та циклічні конструкції мови Python')
    doc.add_paragraph('Мета роботи: Ознайомитись з умовними операторами та циклічними конструкціями мови Python.')

    # 1. Текст завдання
    doc.add_heading('1. Повний текст завдання (Варіант 23)', level=1)
    tasks = [
        "Виправлення помилок у програмі для шифру Цезаря.",
        "Генерація пароля з 5 малих та 4 великих літер.",
        "Математичні обчислення (квадрати, кратні 100, суми парних чисел).",
        "Дешифрування афінного шифру для українського алфавіту.",
        "Brute-force атака на хеш SHA-256 для 6-символьного пароля.",
        "Реалізація генератора Блюм-Блюма-Шуба (BBS) та статистичні тести.",
        "Функції HexDump та DeHex для роботи з байтами."
    ]
    for task in tasks:
        doc.add_paragraph(task, style='List Bullet')

    # 2. Результати
    doc.add_heading('2. Результати роботи програм', level=1)

    # Математика
    doc.add_heading('Математичні операції (Завдання 3)', level=2)
    doc.add_paragraph('Для n = 11432 знайдено суму непарних цифр, яка дорівнює 5.')
    doc.add_paragraph('Сума парних чисел у діапазоні [3174, 10414] обчислена за допомогою циклу for.')

    # Афінний шифр
    doc.add_heading('Афінний шифр (Завдання 4)', level=2)
    doc.add_paragraph('Використано український алфавіт (33 літери).')
    doc.add_paragraph('Для дешифрування знайдено модульне обернене значення параметра a.')
    doc.add_paragraph('Результат дешифрування: "світло наче би зблиснуло, так тихо стало,".')

    # BBS
    doc.add_heading('Генератор BBS (Завдання 6)', level=2)
    doc.add_paragraph('Згенеровано 20,000 біт.')
    doc.add_paragraph('Проведено Monobit test: кількість одиниць та нулів повинна бути в межах 9725-10275.')
    doc.add_paragraph('Long run test: максимальна серія однакових бітів не перевищує 26.')

    # 3. Висновок
    doc.add_heading('3. Висновок', level=1)
    doc.add_paragraph(
        'Під час виконання роботи було вивчено роботу з умовними операторами та циклами Python. '
        'Реалізовано криптографічні алгоритми та методи статистичної перевірки випадкових чисел. '
        'Отримано навички роботи з рядками, байтами та хеш-функціями.'
    )

    # Збереження
    doc.save('Звіт_Лабораторна.docx')
    print("Файл 'Звіт_Лабораторна.docx' успішно створено!")


if __name__ == "__main__":
    create_report()